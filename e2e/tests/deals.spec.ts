import { expect, test } from '../fixtures'
import { api, choose, columnText, dollars, pick, row, rowAction, search, sheet, toast, unique } from '../helpers'

test('[R6, R10, C2] add a deal; it is in the table with its expected revenue, after a reload too', async ({ page }) => {
  const name = unique('Courier app')
  await page.goto('/deals')
  await page.getByRole('button', { name: 'Add deal' }).click()
  await sheet(page).getByLabel('Name').fill(name)
  await pick(page, /Organization/, 'Northbound Couriers')
  await choose(page, 'Stage', 'Proposal')
  await expect(sheet(page).getByLabel('Probability (%)')).toHaveValue('40')
  await sheet(page).getByLabel('Value ($)').fill('45000')
  await sheet(page).getByLabel('Close date').fill('2027-02-15')
  await sheet(page).getByRole('button', { name: 'Add deal' }).click()
  await toast(page, 'Deal added')
  await page.reload()
  await search(page).fill(name)
  const r = row(page, name)
  await expect(r).toContainText('Northbound Couriers')
  await expect(r).toContainText('Proposal')
  await expect(r).toContainText('$45,000')
  await expect(r).toContainText('40%')
  await expect(r).toContainText('$18,000')
  await expect(r).toContainText('Feb 15, 2027')
})

test('[R8, R9, R25, C2, C4] search and sort; expected revenue shows, and late deals show Late', async ({ page, request }) => {
  await page.goto('/deals')
  await page.getByRole('button', { name: 'Value' }).click()
  const values = (await columnText(page, 4)).map(dollars)
  expect(values).toEqual([...values].sort((a, b) => a - b))
  const deals = await api<{ name: string; late: boolean; value: number; probability: number; expected_revenue: number }[]>(request, 'get', '/deals')
  const late = deals.filter((d) => d.late)
  expect(late.length).toBeGreaterThan(0)
  await search(page).fill(late[0].name)
  await expect(row(page, late[0].name).first()).toContainText('Late')
  const sample = deals.find((d) => !d.late && d.value > 0)!
  await search(page).fill(sample.name)
  await expect(row(page, sample.name).first()).toContainText(`$${sample.expected_revenue.toLocaleString('en-US')}`)
  await search(page).fill('negotiation')
  for (const stage of await columnText(page, 3)) expect(stage).toBe('Negotiation')
})

test('[R11, R12, R22, R24, C2] edit in the form: changing the stage changes the probability and adds a timeline entry; delete asks first', async ({ page, request }) => {
  const name = unique('Stage shift')
  const deal = await api<{ id: number }>(request, 'post', '/deals', { name, value: 20000, close_date: '2027-01-10', stage: 'qualified' })
  await page.goto('/deals')
  await search(page).fill(name)
  await rowAction(page, name, 'Edit')
  await expect(sheet(page).getByLabel('Probability (%)')).toHaveValue('20')
  await choose(page, 'Stage', 'Negotiation')
  await expect(sheet(page).getByLabel('Probability (%)')).toHaveValue('70')
  await sheet(page).getByRole('button', { name: 'Save' }).click()
  await toast(page, 'Deal saved')
  await page.reload()
  await search(page).fill(name)
  await expect(row(page, name)).toContainText('Negotiation')
  await expect(row(page, name)).toContainText('70%')

  await page.goto(`/deals/${deal.id}`)
  await expect(page.getByRole('list', { name: 'Timeline' })).toContainText('Moved from Qualified to Negotiation')

  await page.goto('/deals')
  await search(page).fill(name)
  await rowAction(page, name, 'Delete')
  const dialog = page.getByRole('alertdialog')
  await expect(dialog).toContainText(`Delete ${name}?`)
  await expect(dialog).toContainText('1 stage change will be deleted from its history.')
  await dialog.getByRole('button', { name: 'Delete' }).click()
  await toast(page, 'Deal deleted')
  await page.reload()
  await search(page).fill(name)
  await expect(page.getByText(`No deals match "${name}"`)).toBeVisible()
})

test('[R17, C3] the deal page shows all its fields and links', async ({ page, request }) => {
  const org = await api<{ id: number; name: string }>(request, 'post', '/organizations', { name: unique('Pike Hotels') })
  const c = await api<{ id: number; name: string }>(request, 'post', '/contacts', { first_name: 'Ivo', last_name: unique('Brandt').replace(/\s/g, ''), organization_id: org.id })
  const deal = await api<{ id: number; name: string }>(request, 'post', '/deals', { name: unique('Pike booking'), organization_id: org.id, contact_id: c.id, value: 64000, stage: 'proposal', close_date: '2027-03-31' })
  await page.goto(`/deals/${deal.id}`)
  await expect(page.getByRole('heading', { level: 1, name: deal.name })).toBeVisible()
  await expect(page.getByText('Stage: Proposal')).toBeVisible()
  const figures = page.locator('dl').first()
  await expect(figures).toContainText('$64,000')
  await expect(figures).toContainText('40%')
  await expect(figures).toContainText('$25,600')
  await expect(figures).toContainText('Mar 31, 2027')
  await expect(page.getByRole('link', { name: org.name }).first()).toHaveAttribute('href', `/organizations/${org.id}`)
  await expect(page.getByRole('link', { name: c.name }).first()).toHaveAttribute('href', `/contacts/${c.id}`)

  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete' }).click()
  await expect(page).toHaveURL(/\/deals$/)
})
