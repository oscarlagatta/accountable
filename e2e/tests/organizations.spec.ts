import { expect, test } from '../fixtures'
import { api, columnText, dollars, row, rowAction, search, sheet, toast, unique } from '../helpers'

test('[R6, R7, R8, R10, C2] add an organization in the side panel; it is in the table and still there after a reload', async ({ page }) => {
  const name = unique('Bramble Analytics')
  await page.goto('/organizations')
  await expect(page.getByRole('row')).not.toHaveCount(1)
  await page.getByRole('button', { name: 'Add organization' }).click()
  await expect(sheet(page).getByRole('heading', { name: 'Add organization' })).toBeVisible()
  await sheet(page).getByRole('button', { name: 'Add organization' }).click()
  await expect(sheet(page).getByText('Required')).toBeVisible()
  await sheet(page).getByLabel('Name').fill(name)
  await sheet(page).getByLabel(/Website/).fill('bramble.example.com')
  await sheet(page).getByLabel(/Industry/).fill('Software')
  await sheet(page).getByRole('button', { name: 'Add organization' }).click()
  await toast(page, 'Organization added')
  await expect(sheet(page)).toBeHidden()

  await search(page).fill(name.toUpperCase())
  await expect(page.getByRole('row')).toHaveCount(2)
  await expect(row(page, name)).toContainText('Software')

  await page.reload()
  await search(page).fill(name)
  await expect(row(page, name)).toContainText('bramble.example.com')
})

test('[R8, R9, C2] search as you type and sort by headings', async ({ page }) => {
  await page.goto('/organizations')
  const names = await columnText(page, 0)
  expect(names).toEqual([...names].sort((a, b) => a.localeCompare(b, undefined, { sensitivity: 'base' })))
  await expect(page.getByRole('columnheader', { name: /Name/ })).toHaveAttribute('aria-sort', 'ascending')

  await page.getByRole('button', { name: 'Open value' }).click()
  await page.getByRole('button', { name: /Open value/ }).click()
  await expect(page.getByRole('columnheader', { name: /Open value/ })).toHaveAttribute('aria-sort', 'descending')
  const values = (await columnText(page, 5)).map(dollars)
  expect(values).toEqual([...values].sort((a, b) => b - a))

  await search(page).fill('health')
  for (const n of await columnText(page, 0)) expect(n.toLowerCase() + (await row(page, n).textContent())!.toLowerCase()).toContain('health')
  await search(page).fill('zzzz-nothing')
  await expect(page.getByText('No organizations match "zzzz-nothing"')).toBeVisible()
  await page.getByRole('button', { name: 'Clear search' }).click()
  await expect(page.getByRole('row')).not.toHaveCount(1)
})

test('[R11, C2] edit from the row; clicking the row opens the organization', async ({ page, request }) => {
  const name = unique('Edit Me Ltd')
  await api(request, 'post', '/organizations', { name, industry: 'Retail' })
  await page.goto('/organizations')
  await search(page).fill(name)
  await rowAction(page, name, 'Edit')
  await sheet(page).getByLabel(/Industry/).fill('Education')
  await sheet(page).getByLabel(/Notes/).fill('Three campuses')
  await sheet(page).getByRole('button', { name: 'Save' }).click()
  await toast(page, 'Organization saved')
  await page.reload()
  await search(page).fill(name)
  await expect(row(page, name)).toContainText('Education')
  await row(page, name).getByRole('cell').first().click()
  await expect(page).toHaveURL(/\/organizations\/\d+$/)
  await expect(page.getByRole('heading', { level: 1, name })).toBeVisible()
  await expect(page.getByText('Three campuses')).toBeVisible()
})

test('[R12, K1, C2] deleting asks first with counts and leaves contacts and deals with no organization', async ({ page, request }) => {
  const name = unique('Northwind Doomed')
  const org = await api<{ id: number }>(request, 'post', '/organizations', { name })
  const person = await api<{ id: number }>(request, 'post', '/contacts', { first_name: 'Kept', last_name: unique('Person').replace(/\s/g, ''), organization_id: org.id })
  const deal = await api<{ id: number }>(request, 'post', '/deals', { name: unique('Kept deal'), organization_id: org.id, value: 1000, close_date: '2027-01-01' })

  await page.goto('/organizations')
  await search(page).fill(name)
  await rowAction(page, name, 'Delete')
  const dialog = page.getByRole('alertdialog')
  await expect(dialog.getByRole('heading', { name: `Delete ${name}?` })).toBeVisible()
  await expect(dialog).toContainText('1 contact will have no organization.')
  await expect(dialog).toContainText('1 deal will have no organization.')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(row(page, name)).toBeVisible()

  await rowAction(page, name, 'Delete')
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete' }).click()
  await toast(page, 'Organization deleted')
  await page.reload()
  await search(page).fill(name)
  await expect(page.getByText(`No organizations match "${name}"`)).toBeVisible()

  expect((await api<{ organization_id: number | null }>(request, 'get', `/contacts/${person.id}`)).organization_id).toBeNull()
  expect((await api<{ organization_id: number | null }>(request, 'get', `/deals/${deal.id}`)).organization_id).toBeNull()
})

test('[R15, C3] the organization page lists its contacts and deals, and its Add buttons pre-fill it', async ({ page, request }) => {
  const name = unique('Kestrel Partners')
  const org = await api<{ id: number }>(request, 'post', '/organizations', { name, industry: 'Healthcare' })
  await api(request, 'post', '/contacts', { first_name: 'Rita', last_name: 'Moreno', organization_id: org.id, status: 'customer' })
  await api(request, 'post', '/deals', { name: 'Kestrel intake', organization_id: org.id, value: 12000, close_date: '2027-02-01', stage: 'proposal' })

  await page.goto(`/organizations/${org.id}`)
  await expect(page.getByRole('heading', { level: 1, name })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Contacts' }).getByRole('link', { name: 'Rita Moreno' })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Deals' }).getByRole('link', { name: 'Kestrel intake' })).toBeVisible()

  await page.getByRole('button', { name: 'Add contact' }).click()
  await expect(sheet(page).getByRole('combobox', { name: /Organization/ })).toHaveText(name)
  await sheet(page).getByLabel('First name').fill('Sam')
  await sheet(page).getByLabel('Last name').fill('Oduya')
  await sheet(page).getByRole('button', { name: 'Add contact' }).click()
  await expect(page.getByRole('list', { name: 'Contacts' }).getByRole('link', { name: 'Sam Oduya' })).toBeVisible()

  await page.getByRole('button', { name: 'Add deal' }).click()
  await expect(sheet(page).getByRole('combobox', { name: /Organization/ })).toHaveText(name)
  await sheet(page).getByLabel('Name').fill('Kestrel expansion')
  await sheet(page).getByLabel('Value ($)').fill('8000')
  await sheet(page).getByLabel('Close date').fill('2027-03-01')
  await sheet(page).getByRole('button', { name: 'Add deal' }).click()
  await expect(page.getByRole('list', { name: 'Deals' }).getByRole('link', { name: 'Kestrel expansion' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('list', { name: 'Contacts' }).getByRole('link', { name: 'Sam Oduya' })).toBeVisible()
})
